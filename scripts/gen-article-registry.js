/**
 * Generates `lib/generated/articleComponents.js` and syncs per-article assets.
 *
 * Articles are authored as **one folder per article**:
 *
 *   content/blog/<dir>/index.mdx        article body (default language)
 *   content/blog/<dir>/index.en.mdx     English body
 *   content/blog/<dir>/images/**        images, referenced as `images/x.png`
 *   content/blog/<dir>/cover.svg        cover, referenced from frontmatter
 *   content/blog/<dir>/components/**    MDX components for this article only
 *
 * Two things cannot happen at runtime and are therefore prepared here:
 *
 * 1. An MDX component map needs *static imports* on the client - a component
 *    reference cannot travel through `getStaticProps` (props must be
 *    serialisable). So this script writes a registry pairing every article
 *    folder with its `components/index.js`.
 * 2. The site is a static export: only files under `public/` are published.
 *    So article images and covers are copied from the article folder into
 *    `public/blog/<dir>/`, which is generated output (git-ignored).
 *
 * Run via `npm run gen:articles`; `dev` and `build` run it automatically.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const BLOG_DIR = path.join(ROOT, 'content', 'blog');
const PUBLIC_BLOG_DIR = path.join(ROOT, 'public', 'blog');
const OUT_FILE = path.join(ROOT, 'lib', 'generated', 'articleComponents.js');

/** Article *sources* - never copied into `public/`. */
const SOURCE_FILE = /\.(mdx?|jsx?|tsx?|less|css|json)$/i;
/** Folders inside an article that hold sources, not assets. */
const SOURCE_DIRS = new Set(['components']);

function listArticleDirs() {
    if (!fs.existsSync(BLOG_DIR)) return [];

    return fs
        .readdirSync(BLOG_DIR, { withFileTypes: true })
        .filter((entry) => entry.isDirectory())
        .map((entry) => entry.name)
        .sort();
}

/** `2024-post` -> `a2024_post`, so the generated import is always valid JS. */
function toIdentifier(dirName) {
    const cleaned = dirName.replace(/[^A-Za-z0-9_$]/g, '_');
    return /^[A-Za-z_$]/.test(cleaned) ? cleaned : `a_${cleaned}`;
}

function writeRegistry(articleDirs) {
    const withComponents = articleDirs.filter((dirName) =>
        fs.existsSync(path.join(BLOG_DIR, dirName, 'components', 'index.js')),
    );

    const imports = withComponents
        .map(
            (dirName) =>
                `import ${toIdentifier(dirName)} from '../../content/blog/${dirName}/components';`,
        )
        .join('\n');

    const entries = withComponents.map((dirName) => `    ${toIdentifier(dirName)},`).join('\n');

    const content = `/*
 * AUTO-GENERATED by \`scripts/gen-article-registry.js\` - do not edit by hand.
 *
 * Pairs every article folder that ships its own MDX components with those
 * components, so \`templates/BlogPost.js\` can look them up by \`dirName\`.
 * Regenerate with \`npm run gen:articles\`.
 */
${imports ? `\n${imports}\n` : ''}
/** Maps an article \`dirName\` to the extra components its MDX may use. */
const articleComponents = {${entries ? `\n${entries}\n` : ''}};

export default articleComponents;
`;

    fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
    const previous = fs.existsSync(OUT_FILE) ? fs.readFileSync(OUT_FILE, 'utf8') : null;
    if (previous !== content) fs.writeFileSync(OUT_FILE, content);

    return withComponents.length;
}

function copyAssets(dirName) {
    const sourceDir = path.join(BLOG_DIR, dirName);
    const targetDir = path.join(PUBLIC_BLOG_DIR, dirName);

    // Rebuilt from scratch so that deleting an image in the article folder also
    // removes the published copy - the two can never drift apart.
    fs.rmSync(targetDir, { recursive: true, force: true });

    let copied = 0;
    const walk = (from, to) => {
        fs.readdirSync(from, { withFileTypes: true }).forEach((entry) => {
            if (entry.isDirectory()) {
                if (SOURCE_DIRS.has(entry.name)) return;
                walk(path.join(from, entry.name), path.join(to, entry.name));
                return;
            }
            if (SOURCE_FILE.test(entry.name)) return;

            fs.mkdirSync(to, { recursive: true });
            fs.copyFileSync(path.join(from, entry.name), path.join(to, entry.name));
            copied += 1;
        });
    };

    walk(sourceDir, targetDir);

    // Article without images or cover: leave nothing behind in `public/`.
    if (copied === 0) fs.rmSync(targetDir, { recursive: true, force: true });

    return copied;
}

function main() {
    const articleDirs = listArticleDirs();
    const registrySize = writeRegistry(articleDirs);
    const assetCount = articleDirs.reduce((total, dirName) => total + copyAssets(dirName), 0);

    process.stdout.write(
        `[gen:articles] ${articleDirs.length} article folder(s), ` +
        `${registrySize} with components, ${assetCount} asset(s) published\n`,
    );
}

main();
